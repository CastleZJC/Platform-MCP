"""本地生成模型栈（V3.0 M4.1，架构 §19.5.6 / 计划 M4.1、F-35、VNF-01、VNF-03）

Web 端本地生成通道：Qwen3-4B-Instruct GGUF 经 llama-cpp-python（纯 CPU，无 GPU/torch 依赖），
产出中英双语审核报告、英文 README 与分享迭代差异描述；CC+MCP 外部通道（glm 5.3）不经过本模块
（外部产物经 MCP ``submit_skill_artifact`` 回传 + 平台重放校验存档，F-36）。

设计与 :mod:`platform_mcp.skills.embedding`（M3 向量栈）同构：

- **权重离线分发**（VNF-03）：``settings.skill.llm_model_path`` 指向离线 GGUF 文件；非空且
  llama-cpp-python 可导入/加载时启用，任何异常（依赖缺失、权重不存在、加载失败）降级为不可用，
  绝不联网下载。
- **单槽信号量**：本地模型 CPU 推理串行化——事件循环层 ``asyncio.Semaphore(1)`` 排队 +
  线程层 ``threading.Lock`` 防并发推理同一 ``Llama`` 实例（VNF-01 性能有限，逐条生成）。
- **超时兜底**（VNF-01）：单次生成 ``asyncio.wait_for`` 超时（默认 60s，可按调用覆盖）即放弃
  本次结果（底层线程自然结束后释放线程锁），调用方捕获 :class:`LlmGenerationError` 走确定性模板。
- **进程级单例**：``get_llm_provider()`` 选定后缓存（静态配置，切换权重需重启，§19.5.2）；
  ``reset_llm_provider()`` 为测试钩子。

产物来源留痕（``pmcp_skill_version.generated_by``，F-35）：

- ``template``：确定性模板兜底（M2 以来默认）；
- ``model``：本地 Qwen3-4B 生成（Web 通道，本模块）；
- ``external``：MCP 通道外部大模型（glm 5.3）回传产物（ecosystem 工具层写入）。

性能提示（M4.4，F-35「全程提示」）：本地模型产物与差异描述附带固定提示文案
「本地模型生成，性能有限，建议使用外部大模型（CC+MCP 通道）」。
"""

